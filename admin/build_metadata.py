def clean(text: str) -> str:
    text = re.sub(r"\s+", "", text)
    for old, new in REPLACEMENTS.items():
        text = text.replace(old, new)
    return text


def best_match(texts: list[str], choices: list[str], threshold: float = 0.58) -> str:
    candidates = [clean(text) for text in texts]
    best_name, best_score = "", 0.0
    for name in choices:
        target = clean(name)
        for text in candidates:
            if target in text:
                return name
            score = SequenceMatcher(None, target, text).ratio()
            if score > best_score:
                best_name, best_score = name, score
    return best_name if best_score >= threshold else "ไม่ระบุจากภาพ"


def institution_type(institution: str) -> str:
    if "ทหาร" in institution or "ตำรวจ" in institution:
        return "ทหาร/ตำรวจ"
    if "มหาวิทยาลัย" in institution or "สถาบัน" in institution:
        return "มหาวิทยาลัย"
    if "วิทยาลัย" in institution or "โรงเรียน" in institution:
        return "วิทยาลัย"
    if institution == "ไม่ระบุจากภาพ":
        return "ไม่ระบุ"
    return "มหาวิทยาลัย/สถาบัน"


def main() -> None:
    source = json.loads(OCR_FILE.read_text(encoding="utf-8"))
    result = []
    for item in source:
        texts = item["texts"]
        institution = best_match(texts, INSTITUTIONS)
        faculty = best_match([text for text in texts if "คณะ" in clean(text)], FACULTIES)
        if not faculty:
            faculty = "ไม่ระบุจากภาพ"
        overrides = {
            "bkw2568/fromfb_a_880042917880048_012.jpg": ("โรงเรียนเอื้อการย์บริบาลและภาษา", "ผู้ช่วยพยาบาล"),
            "bkw2566/fromfb_a_251974787353534_026.jpg": ("โรงเรียนจุฬารัตน์อินเตอร์เฮลท์", "ผู้ช่วยพยาบาล"),
        }
        if item["path"] in overrides:
            institution, faculty = overrides[item["path"]]
        result.append({
            "year": 2565 if item["path"].startswith("bkw2566/") else item["year"],
            "path": item["path"],
            "institution": institution,
            "institutionType": institution_type(institution),
            "faculty": faculty,
            "ocrText": " ".join(texts),
        })
    OUTPUT.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"สร้าง {OUTPUT.name} แล้ว {len(result)} รายการ".encode("ascii", "backslashreplace").decode("ascii"))


if __name__ == "__main__":
    main()
